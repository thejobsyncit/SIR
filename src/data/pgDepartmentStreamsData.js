// Helper functions
export const getPgStreamById = (streamId) => {
  return PG_DEPARTMENT_STREAMS.find(s => s.id === streamId);
};

export const getPgCoursesByStream = (streamId) => {
  return PG_COURSES_CATALOGUE.filter(c => c.streamId === streamId);
};

export const getPgCoursesByDegree = (streamId, degreeAbbr) => {
  const targetAbbr = typeof degreeAbbr === 'object' && degreeAbbr !== null ? (degreeAbbr.abbr || degreeAbbr.id) : degreeAbbr;
  return PG_COURSES_CATALOGUE.filter(c => {
    if (streamId && c.streamId !== streamId) return false;
    if (!targetAbbr || targetAbbr === 'all') return true;
    return c.degrees.some(d => d.toLowerCase() === targetAbbr.toLowerCase());
  });
};
