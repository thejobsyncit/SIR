// Helper Functions
export const getAllCourses = () => COURSES_CATALOGUE;

export const getCourseById = (id) => {
  return COURSES_CATALOGUE.find(c => c.id === id) || null;
};

export const getCoursesByCategory = (categoryId) => {
  if (!categoryId || categoryId === 'all') return COURSES_CATALOGUE;
  return COURSES_CATALOGUE.filter(c => c.categoryId === categoryId);
};

export const getCoursesByLevel = (level) => {
  if (!level || level === 'all') return COURSES_CATALOGUE;
  return COURSES_CATALOGUE.filter(c => c.level === level);
};

export const getRelatedCourses = (courseId) => {
  const current = getCourseById(courseId);
  if (!current) return [];
  
  if (current.relatedCourseIds && current.relatedCourseIds.length > 0) {
    const directMatches = current.relatedCourseIds
      .map(id => getCourseById(id))
      .filter(Boolean);
    if (directMatches.length > 0) return directMatches;
  }

  // Fallback: match same department
  return COURSES_CATALOGUE.filter(c => c.categoryId === current.categoryId && c.id !== current.id).slice(0, 3);
};

export const getCategoryCounts = () => {
  const counts = { all: COURSES_CATALOGUE.length };
  ACADEMIC_CATEGORIES.forEach(cat => {
    counts[cat.id] = COURSES_CATALOGUE.filter(c => c.categoryId === cat.id).length;
  });
  return counts;
};
