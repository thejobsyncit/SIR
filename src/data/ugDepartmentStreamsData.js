export const getStreamById = (streamId) => {
  return UG_DEPARTMENT_STREAMS.find(s => s.id === streamId);
};

export const getCoursesByStream = (streamId) => {
  return UG_COURSES_CATALOGUE.filter(c => c.streamId === streamId);
};

export const getCoursesByDegree = (streamId, degreeAbbr) => {
  return UG_COURSES_CATALOGUE.filter(c => {
    if (streamId && c.streamId !== streamId) return false;
    if (!degreeAbbr || degreeAbbr === 'all') return true;
    return c.degrees.some(d => d.toLowerCase() === degreeAbbr.toLowerCase());
  });
};
